_DETECTORS = {
    'log': (_log_features, _NORMAL_LOGS),
    'network': (_network_features, _NORMAL_NETWORK),
    'user': (_user_behavior_features, _NORMAL_USER),
}


def _evaluate_detector(feature_fn, training_samples, labeled_samples):
    model = IsolationForest(contamination=0.1, random_state=42, n_estimators=100)
    model.fit(np.asarray([feature_fn(sample) for sample in training_samples]))

    texts = labeled_samples['normal'] + labeled_samples['anomaly']
    labels = [0] * len(labeled_samples['normal']) + [1] * len(labeled_samples['anomaly'])
    predictions = [
        int(value == -1)
        for value in model.predict(np.asarray([feature_fn(text) for text in texts]))
    ]
    true_negative, false_positive, false_negative, true_positive = confusion_matrix(
        labels, predictions, labels=[0, 1]
    ).ravel()

    return {
        'training_samples': len(training_samples),
        'evaluation_samples': len(texts),
        'normal_samples': len(labeled_samples['normal']),
        'anomaly_samples': len(labeled_samples['anomaly']),
        'accuracy': accuracy_score(labels, predictions),
        'precision': precision_score(labels, predictions, zero_division=0),
        'recall': recall_score(labels, predictions, zero_division=0),
        'f1': f1_score(labels, predictions, zero_division=0),
        'confusion_matrix': {
            'true_negative': int(true_negative),
            'false_positive': int(false_positive),
            'false_negative': int(false_negative),
            'true_positive': int(true_positive),
        },
    }


def evaluate_models():
    return {
        'dataset': 'built-in synthetic examples; not a measure of production detection accuracy',
        'models': {
            name: _evaluate_detector(feature_fn, training_samples, LABELED_EVALUATION[name])
            for name, (feature_fn, training_samples) in _DETECTORS.items()
        },
    }


if __name__ == '__main__':
    print(json.dumps(evaluate_models(), indent=2))
